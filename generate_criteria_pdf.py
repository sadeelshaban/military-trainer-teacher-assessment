def ar(text: str) -> str:
    if not text:
        return ""
    return get_display(arabic_reshaper.reshape(text))


class ArabicPDF(FPDF):
    def __init__(self):
        super().__init__()
        self.add_font("Tahoma", "", FONT_PATH)
        self.set_auto_page_break(auto=True, margin=20)

    def content_width(self) -> float:
        return self.w - self.l_margin - self.r_margin

    def rtl_multi(self, h, txt, align="R"):
        self.set_x(self.l_margin)
        self.set_font("Tahoma", "", 11)
        self.multi_cell(self.content_width(), h, ar(txt), align=align)

    def section_title(self, title: str):
        self.ln(4)
        self.set_x(self.l_margin)
        self.set_fill_color(30, 58, 95)
        self.set_text_color(255, 255, 255)
        self.set_font("Tahoma", "", 14)
        self.cell(self.content_width(), 10, ar(title), new_x="LMARGIN", new_y="NEXT", align="C", fill=True)
        self.set_text_color(0, 0, 0)
        self.ln(2)

    def criterion_block(self, number: int, name: str, desc: str, indicators: list[str]):
        w = self.content_width()
        self.set_x(self.l_margin)
        self.set_font("Tahoma", "", 12)
        self.set_text_color(30, 58, 95)
        self.multi_cell(w, 7, ar(f"{number}. {name}"), align="R")
        self.set_text_color(0, 0, 0)
        self.set_font("Tahoma", "", 11)
        self.multi_cell(w, 6, ar(f"التعريف: {desc}"), align="R")
        self.set_font("Tahoma", "", 10)
        self.set_text_color(60, 60, 60)
        self.multi_cell(w, 5, ar("مؤشرات السلوك:"), align="R")
        for ind in indicators:
            self.multi_cell(w, 5, ar(f"  • {ind}"), align="R")
        self.set_text_color(0, 0, 0)
        self.ln(2)


